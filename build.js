// Writes assets.js: the stylesheet with the fonts inlined, as one string, so
// the theme reads no files when it renders. `node build.js --check` fails
// instead of writing when assets.js is out of date.
const fs = require("fs");
const path = require("path");

const read = (file, encoding) => fs.readFileSync(path.join(__dirname, file), encoding);

const FACES = [
  ["Source Serif 4", "normal", "200 900", "SourceSerif4-Roman.woff2"],
  ["Source Serif 4", "italic", "200 900", "SourceSerif4-Italic.woff2"],
  ["Inter", "normal", "100 900", "Inter.woff2"],
];

const css =
  FACES.map(
    ([family, style, weight, file]) =>
      `@font-face { font-family: "${family}"; font-style: ${style}; font-weight: ${weight}; ` +
      `src: url(data:font/woff2;base64,${read(`fonts/${file}`, "base64")}) format("woff2"); }`,
  ).join("\n") +
  "\n" +
  read("style.css", "utf-8");

const output = `// Generated by build.js from style.css and fonts/. Do not edit.\nmodule.exports = { css: ${JSON.stringify(css)} };\n`;
const target = path.join(__dirname, "assets.js");

if (process.argv.includes("--check")) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf-8") : "";
  if (current !== output) {
    console.error("assets.js is out of date: run npm run build and commit it.");
    process.exit(1);
  }
} else {
  fs.writeFileSync(target, output);
  console.log("Wrote assets.js");
}
